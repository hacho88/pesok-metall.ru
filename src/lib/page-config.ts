// Читает конфиг страницы из БД; при недоступности БД — дефолтный JSON (витрина не падает)
export async function getPageConfig(slug: string): Promise<PageConfig> {
  try {
    const row = await prisma.pageConfig.findUnique({ where: { slug } });
    if (row) {
      return {
        slug: row.slug,
        theme: (row.theme as ThemePreset) ?? DEFAULT_PAGE_CONFIG.theme,
        blocks: (row.blocks as unknown as PageBlock[]) ?? DEFAULT_PAGE_CONFIG.blocks,
      };
    }
  } catch {
    // БД недоступна (например, dev без PostgreSQL) — рендерим дефолтную витрину
  }
  return DEFAULT_PAGE_CONFIG;
}
